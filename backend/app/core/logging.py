# ==========================================================================
# Purpose: Set Up Logging
# ==========================================================================
# IMPORTS & MODULE LOADING
# ==========================================================================
import logging


# ==========================================================================
# CORE LOGIC & FUNCTIONS
# ==========================================================================
def setup_logging() -> None:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )
